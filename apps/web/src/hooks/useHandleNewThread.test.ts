import { useNewThreadHandler } from "./useHandleNewThread";

describe.each([
  ["new", null],
  [
    "reusable",
    {
      draftId: "draft-existing",
      environmentId: "environment-ssh",
      promotedTo: null,
      threadId: "thread-existing",
    },
  ],
])("useNewThreadHandler with a %s draft", (_, draft) => {
  it.each(["approval-required", "auto-accept-edits", "auto", "full-access"] as const)(
    "uses the target environment's %s permissions for new threads",
    async (runtimeMode) => {
      testState.reset(draft);
      testState.targetSettings.defaultRuntimeMode = runtimeMode;
      const projectRef = {
        environmentId: "environment-ssh",
        projectId: "project-remote",
      } as never;
      const pendingOpen = useNewThreadHandler()(projectRef);
      testState.completeProjectFileRead(null);
      const opened = await pendingOpen;

      expect(testState.draftStore.setLogicalProjectDraftThreadId).toHaveBeenCalledWith(
        "remote-project",
        projectRef,
        opened!.draftId,
        expect.objectContaining({ runtimeMode }),
      );
    },
  );

  it("abandons a delayed draft open when the user navigates elsewhere", async () => {
    testState.reset(draft);
    const openThread = useNewThreadHandler();
    const pendingOpen = openThread(
      { environmentId: "environment-ssh", projectId: "project-remote" } as never,
      { replace: true },
    );

    testState.router.state.location.href = "/usage";
    testState.completeProjectFileRead(null);
    await pendingOpen;

    expect(testState.router.state.location.href).toBe("/usage");
    expect(testState.router.navigate).not.toHaveBeenCalled();
    expect(testState.draftStore.setLogicalProjectDraftThreadId).not.toHaveBeenCalled();
  });

  it.each([true, false])(
    "uses the target environment's start-from-origin default of %s",
    async (startFromOrigin) => {
      testState.reset(draft, { envMode: "worktree", startFromOrigin });
      const openThread = useNewThreadHandler();
      const projectRef = {
        environmentId: "environment-ssh",
        projectId: "project-remote",
      } as never;
      const pendingOpen = openThread(projectRef);

      testState.completeProjectFileRead(null);
      const opened = await pendingOpen;

      expect(opened).toEqual({
        draftId: draft?.draftId ?? "draft-delayed",
        threadId: draft?.threadId ?? "thread-delayed",
      });
      expect(testState.draftStore.setLogicalProjectDraftThreadId).toHaveBeenCalledWith(
        "remote-project",
        projectRef,
        opened!.draftId,
        expect.objectContaining({ envMode: "worktree", startFromOrigin }),
      );
      if (draft) {
        expect(testState.draftStore.setDraftThreadContext).toHaveBeenCalledWith(
          draft.draftId,
          expect.objectContaining({ envMode: "worktree", startFromOrigin }),
        );
      }
    },
  );

  it.each([true, false])(
    "preserves an explicit start-from-origin choice of %s",
    async (startFromOrigin) => {
      testState.reset(draft, { envMode: "worktree", startFromOrigin: !startFromOrigin });
      const openThread = useNewThreadHandler();
      const projectRef = {
        environmentId: "environment-ssh",
        projectId: "project-remote",
      } as never;

      const opened = await openThread(projectRef, { envMode: "worktree", startFromOrigin });

      expect(testState.draftStore.setLogicalProjectDraftThreadId).toHaveBeenCalledWith(
        "remote-project",
        projectRef,
        opened!.draftId,
        expect.objectContaining({ envMode: "worktree", startFromOrigin }),
      );
    },
  );
});

it("registers intrinsic Local visibility before deferred navigation makes a continuation draft sendable", async () => {
  testState.reset(null);
  let completeNavigation!: () => void;
  const navigation = new Promise<void>((resolve) => {
    completeNavigation = resolve;
  });
  let entered!: () => void;
  const navigating = new Promise<void>((resolve) => {
    entered = resolve;
  });
  testState.router.navigate.mockImplementationOnce(async () => {
    const registration = (
      testState.draftStore.setLogicalProjectDraftThreadId.mock.calls as ReadonlyArray<
        ReadonlyArray<unknown>
      >
    ).at(-1);
    expect(registration?.[3]).toMatchObject({ teamLocalOnly: true, envMode: "local" });
    entered();
    await navigation;
    testState.router.state.location.href = "/draft/draft-delayed";
    testState.router.state.matches = [{ params: { draftId: "draft-delayed" } }];
  });
  const handler = useNewThreadHandler();
  const pending = handler(
    { environmentId: "environment-ssh", projectId: "project-remote" } as Parameters<
      typeof handler
    >[0],
    { envMode: "local", teamLocalOnly: true, canCreate: async () => true },
  );
  await navigating;
  expect(
    (
      testState.draftStore.setLogicalProjectDraftThreadId.mock.calls as ReadonlyArray<
        ReadonlyArray<unknown>
      >
    ).at(-1)?.[3],
  ).toMatchObject({ teamLocalOnly: true });
  completeNavigation();
  expect(await pending).toEqual({ draftId: "draft-delayed", threadId: "thread-delayed" });
});

it("does not register or navigate a continuation draft after its source guard fails", async () => {
  testState.reset(null);
  const handler = useNewThreadHandler();
  const opened = await handler(
    { environmentId: "environment-ssh", projectId: "project-remote" } as Parameters<
      typeof handler
    >[0],
    { envMode: "local", teamLocalOnly: true, canCreate: async () => false },
  );
  expect(opened).toBeNull();
  expect(testState.draftStore.setLogicalProjectDraftThreadId).not.toHaveBeenCalled();
  expect(testState.router.navigate).not.toHaveBeenCalled();
});

it("rechecks a continuation scope before its draft registration", async () => {
  testState.reset(null);
  let release!: (value: boolean) => void;
  const checking = new Promise<boolean>((resolve) => {
    release = resolve;
  });
  let entered!: () => void;
  const ready = new Promise<void>((resolve) => {
    entered = resolve;
  });
  let checks = 0;
  const handler = useNewThreadHandler();
  const pending = handler(
    { environmentId: "environment-ssh", projectId: "project-remote" } as Parameters<
      typeof handler
    >[0],
    {
      envMode: "local",
      teamLocalOnly: true,
      canCreate: async () => {
        if (++checks === 1) return true;
        entered();
        return checking;
      },
    },
  );
  await ready;
  expect(testState.draftStore.setLogicalProjectDraftThreadId).not.toHaveBeenCalled();
  release(false);
  expect(await pending).toBeNull();
  expect(testState.router.navigate).not.toHaveBeenCalled();
});
